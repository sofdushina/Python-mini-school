#Напиши рекурсивную функцию sum_digits(n), 
# которая возвращает сумму цифр неотрицательного целого числа. 
# Подумай: какая база и как отрезать последнюю цифру (помнишь % и //?). 
# Проверка: sum_digits(4715) → 17.

def sum_digits(n):
    if n ==0:
        return 0
    return n%10 + sum_digits(n//10) 
print (sum_digits(4715))