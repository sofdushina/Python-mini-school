import pandas as pd
import matplotlib.pyplot as plt
 
data = {
    "товар":      ["Ручка", "Тетрадь", "Папка", "Маркер", "Блокнот",
                   "Скрепки", "Степлер", "Линейка", "Клей", "Ножницы"],
    "категория":  ["письменные", "бумага", "бумага", "письменные", "бумага",
                   "офис", "офис", "офис", "офис", "офис"],
    "цена":       [30, 45, 60, 80, 120, 25, 250, 35, 55, 90],
    "количество": [100, 80, None, 60, 40, 200, 15, None, 70, 30],
}
df = pd.DataFrame(data)

# Задача 1
# Знакомство и очистка. Выведи форму таблицы, типы столбцов и describe(). 
# Найди, в каких столбцах есть пропуски и сколько их. 
# Заполни пропуски в столбце количество медианой (результат запиши обратно в столбец) 
# и убедись, что пропусков не осталось.

print(f"форма таблицы: {df.shape}")
print(f"типы столбцов: {df.dtypes}")
print(f"статистика по числовым столбцам: {df.describe()}")

print(f"в каких столбцах есть пропуски и сколько их: {df.isna().sum()}")

d = df.copy()
d["количество"] = d["количество"].fillna(d["количество"].median())
print(f"в каких столбцах есть пропуски и сколько их после заполнения: {d.isna().sum()}")



# Задача 2
# Новый столбец и фильтр. 
# Добавь столбец выручка = цена × количество. 
# Выведи товары, у которых выручка больше 4000, и топ-3 товара по выручке (только названия и выручка, по убыванию). 
# Затем выведи все товары категории офис с ценой ниже 100.

d["выручка"] = d["цена"] * d["количество"]
print(f"товары, у которых выручка больше 4000: \n{d[d["выручка"] > 4000]}")

d_sort = d.sort_values("выручка", ascending=False).head(3)
print(f'топ-3 товара по выручке: \n{d_sort[["товар", "выручка"]]}')   

print(f"все товары категории офис с ценой ниже 100: {d[(d["категория"] == "офис") & (d["цена"] < 100)]}")

# Задача 3
# Группы и графики. 
# Для каждой категории посчитай через groupby суммарную выручку и среднюю цену (в одной таблице через agg). 
# Построй картинку из двух графиков рядом (plt.subplots(1, 2)): 
# столбцы суммарной выручки по категориям и гистограмма цен всех товаров. Подпиши заголовки и оси, сохрани в report.png. 

print(d.groupby('категория').agg(
    суммарная_выручка = ('выручка','sum'),
    средняя_цена = ('цена', 'mean'),
))

total_revenue = d.groupby("категория")["выручка"].sum()
fig, axes = plt.subplots(1,2)
total_revenue.plot(kind = 'bar', 
                   ax = axes[0], 
                   title = 'суммарная выручка по категориям', 
                   color = 'tab:green', 
                   ylabel = 'рубли', 
                   rot = 0)

d['цена'].plot(kind = 'hist', 
               bins = 5, 
               ax = axes[1],
               ylabel = 'рубли',
               xlabel = 'цена',
               title = 'средняя цена')

plt.tight_layout()
plt.savefig("report.png", dpi = 130)
plt.show()
