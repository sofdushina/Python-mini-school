# 5.	Простые числа. Выведи все простые числа от 2 до 100, используя for … else.
for i in range (2,101):
    for j in range (2,i):  #Для каждого i внутренний цикл ищет делитель среди чисел от 2 до i - 1
        if i%j == 0:
            break    #делителя нет, цикл дошёл до конца без break → срабатывает else, и i печатается.
    else: 
        print (i)   #Для i = 2 диапазон range(2, 2) пустой, break не случается, поэтому else выводит 2. 

