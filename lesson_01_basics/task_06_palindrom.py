# 6.	Палиндром. Проверь, является ли введённое слово палиндромом (например, «шалаш») с помощью срезов. 
#Усложнение: игнорируй регистр и пробелы («А роза упала на лапу Азора»).

phrase = str(input("Введи фразу: "))
clean = phrase.lower().replace(' ','') #игнорирую регистр и пробелы
if clean == clean[::-1]:
    print("Палиндром")
else: 
    print("Не палиндром")



             
