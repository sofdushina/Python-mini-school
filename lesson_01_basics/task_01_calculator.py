#1.Калькулятор. Пользователь вводит два числа.
#Выведи их сумму, разность, произведение, частное, целочисленное частное, 
#остаток и первое число в степени второго.
a = int(input("Первое число: "))
b = int(input("Второе число: "))

summ = a+b
diff = a-b
mult = a*b
part = a/b
part_int = a//b
rest = a%b
degree = a**b
print(f"Сумма: {summ}\nРазность: {diff}\nПроизведение: {mult}\nЧастное: {part}\nЦелочисленное частное: {part_int}\nОстаток: {rest}\nСтепень: {degree}")
