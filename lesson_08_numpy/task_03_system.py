# Реши систему 2x + y = 5, x − y = 1 через np.linalg.solve. 
# Проверь ответ умножением A @ v и объясни в комментарии, 
# почему результат может отличаться от целого на очень маленькую величину. 

import numpy as np

A = np.array([[2, 1],
             [1, -1]])
b = np.array([5, 1])

v = np.linalg.solve(A,b)
print(f"ответ системы: {v}")
print (f"проверка: {A @ v}") #Компьютер хранит дробные числа приближённо, поэтому вместо ровно 2 иногда получается 1.9999999999999998.
